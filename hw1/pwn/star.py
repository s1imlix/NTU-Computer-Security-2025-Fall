def read_to_stack():
    """
    read from stdin to stack in hex (max 16 characters) 
    stack[-1] = bytes.fromhex(input())
    """
    return p8(0x60)

def load_to_stack(value, signed=False):
    """
    load immediate value to stack in bytes 
    stack.push(<8-byte>)
    usage: 0x10 <8-byte> 
    """
    b = b""
    b += p8(0x10)  # LOAD
    b += p64(value, signed=signed) 
    return b 

def pop_stack():
    """
    pop top stack value 
    stack.pop()
    """
    return p8(0x11)

def dup_stack(pos):
    """
    duplicate stack value at position pos (0-indexed from top)
    stack.push(stack[-(pos+1)])
    usage: 0x12 <pos>
    """
    return p8(0x12) + p8(pos)

def stack_to_storage():
    """
    0x000000000102f615 around
    mov    rsi, qword ptr [rax + rdi*8 + 0x8008]
    mov    qword ptr [rax + rdx*8], rsi              

    rax: storage
    rax + 0x8008: stack 

    rdx = top-most qword
    rsi = second top-most qword
    -> storage[stack[-1]] = stack[-2]
    """
    return p8(0x13)

def read_from_storage():
    """
    read from storage to stack 
    index = stack.pop()
    stack.push(storage[index])
    """
    return p8(0x14)

def add_stack():
    """
    add top two stack values 
    a = stack.pop()
    b = stack.peek()
    stack.push(a + b)
    """
    return p8(0x20)

def or_stack():
    """
    or top two stack values 
    a = stack.pop()
    b = stack.peek()
    stack.push(a | b)
    """
    return p8(0x31)

def xor_stack():
    """
    xor top two stack values 
    a = stack.pop()
    b = stack.pop()
    stack.push(a ^ b)
    """
    return p8(0x32)

def sub_stack():
    """
    sub top two stack values 
    a = stack.pop()
    b = stack.peek()
    stack.push(a - b)
    """
    return p8(0x40)

def jump_by_offset(offset):
    """
    jump by offset 
    PC += offset
    usage: 0x43 <offset>
    """
    return p8(0x43) + p8(offset)

